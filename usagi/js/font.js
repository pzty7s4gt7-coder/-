  def('ケ', '.#...|.####|#..#.|...#.|..#..');
  def('コ', '#####|....#|....#|....#|#####');
  def('サ', '.#.#.|#####|.#.#.|...#.|.##..');
  def('シ', '##..#|....#|##.#.|..#..|##...');
  def('ス', '#####|....#|...#.|..##.|##..#');
  def('セ', '.#...|#####|.#..#|.#...|..###');
  def('ソ', '#...#|.#..#|....#|...#.|.##..');
  def('タ', '.#...|.####|#.#.#|...#.|.##..');
  def('チ', '..##.|##...|#####|..#..|.#...');
  def('ツ', '#.#.#|#.#.#|....#|...#.|.##..');
  def('テ', '.###.|.....|#####|..#..|.#...');
